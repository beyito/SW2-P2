-- ====================================================================
-- DDL para ms-crm: facturación por eventos, canje de puntos y notas de crédito
-- Script idempotente: se puede ejecutar en cada arranque.
-- ====================================================================

-- 1. Libro de puntos: source_ref impide aplicar dos veces el mismo movimiento
ALTER TABLE loyalty_transactions ADD COLUMN IF NOT EXISTS source_ref VARCHAR(100);
CREATE UNIQUE INDEX IF NOT EXISTS uq_loyalty_source_ref ON loyalty_transactions (source_ref) WHERE source_ref IS NOT NULL;

ALTER TABLE loyalty_transactions DROP CONSTRAINT IF EXISTS loyalty_transactions_type_check;
ALTER TABLE loyalty_transactions ADD CONSTRAINT loyalty_transactions_type_check
    CHECK (type IN ('ACCUMULATION', 'REDEMPTION', 'REVERSAL', 'ADJUSTMENT'));

-- 2. Facturas vinculadas a la SAGA: una por reserva pagada
ALTER TABLE invoices ADD COLUMN IF NOT EXISTS saga_id VARCHAR(36);
ALTER TABLE invoices ADD COLUMN IF NOT EXISTS service_name VARCHAR(100);
ALTER TABLE invoices ADD COLUMN IF NOT EXISTS subtotal_amount NUMERIC(10, 2);
ALTER TABLE invoices ADD COLUMN IF NOT EXISTS discount_amount NUMERIC(10, 2) NOT NULL DEFAULT 0;
ALTER TABLE invoices ADD COLUMN IF NOT EXISTS payment_reference VARCHAR(100);
ALTER TABLE invoices ADD COLUMN IF NOT EXISTS invoice_number BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX IF NOT EXISTS uq_invoices_saga ON invoices (saga_id) WHERE saga_id IS NOT NULL;

ALTER TABLE invoices DROP CONSTRAINT IF EXISTS invoices_status_check;
ALTER TABLE invoices ADD CONSTRAINT invoices_status_check
    CHECK (status IN ('ISSUED', 'CANCELLED', 'PAID', 'REFUNDED'));

-- 3. Notas de crédito: anulan una factura al reembolsarla
CREATE TABLE IF NOT EXISTS credit_notes (
    id VARCHAR(36) PRIMARY KEY,
    credit_note_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
    invoice_id VARCHAR(36) NOT NULL UNIQUE REFERENCES invoices(id),
    client_id VARCHAR(36) NOT NULL REFERENCES crm_clients(id),
    amount NUMERIC(10, 2) NOT NULL CHECK (amount >= 0),
    tax_amount NUMERIC(10, 2) NOT NULL CHECK (tax_amount >= 0),
    reason VARCHAR(255) NOT NULL,
    issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_credit_notes_client ON credit_notes (client_id);
